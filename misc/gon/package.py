#!/usr/bin/env python3
"""Package a built native Gon toolchain, documentation and licenses."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parents[2]


def output(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', required=True)
    parser.add_argument('--output', type=Path, default=ROOT / 'pkg/gon-release')
    args = parser.parse_args()
    if not re.fullmatch(r'2\.27\.\d+(?:-[a-zA-Z0-9.-]+)?', args.version):
        parser.error('version must identify a Gon 2.27 release')
    args.output.mkdir(parents=True, exist_ok=True)
    suffix = '.exe' if os.name == 'nt' else ''
    gon = ROOT / 'gon/bin' / ('gon' + suffix)
    environment = dict(os.environ)
    for name in ('GOOS', 'GOARCH', 'GOROOT', 'GOTOOLDIR'):
        environment.pop(name, None)
    target = json.loads(subprocess.check_output(
        [str(gon), 'env', '-json', 'GOHOSTOS', 'GOHOSTARCH', 'GOVERSION'],
        env=environment, text=True))
    platform = target['GOHOSTOS'] + '-' + target['GOHOSTARCH']
    private = ROOT / 'pkg/tool' / platform.replace('-', '_')
    required = [ROOT / 'bin' / ('go' + suffix), ROOT / 'bin' / ('gofmt' + suffix),
                gon, ROOT / 'gon/bin' / ('gonpls' + suffix),
                *[private / (name + suffix) for name in ('compile', 'link', 'gonpls')]]
    for path in required:
        if not path.is_file():
            raise SystemExit(f'Missing built tool: {path}')
    # Select published source, not local working files or arbitrary build output.
    selected = subprocess.check_output([
        'git', 'ls-files', '-z', '--', 'src', 'lib', 'api', 'go.env', 'LICENSE',
        'PATENTS', 'README.md', 'doc/gon-examples.md', 'doc/gon_logo.png',
        'doc/install.md', 'doc/containers.md', '.agents/skills/gon',
        'misc/gon/install.py', 'misc/gon/*.md', 'misc/gon/features.json',
        'misc/gon/UPSTREAM.json', 'misc/gon/readme-examples',
        'misc/gon/benchmarks/README.md', 'misc/gon/benchmarks/results',
        'misc/gon/validation', 'tools/*/LICENSE', 'tools/*/NOTICE',
    ], cwd=ROOT).decode().split('\0')
    files = {ROOT / name for name in selected if name}
    # These sources are generated by make.bash and are needed when building std.
    generated = [
        'src/cmd/cgo/zdefaultcc.go', 'src/cmd/go/internal/cfg/zdefaultcc.go',
        'src/cmd/internal/objabi/zbootstrap.go', 'src/go/build/zcgo.go',
        'src/internal/buildcfg/zbootstrap.go', 'src/internal/runtime/sys/zversion.go',
        'src/time/tzdata/zzipdata.go',
    ]
    files.update(ROOT / name for name in generated if (ROOT / name).is_file())
    for directory in (ROOT / 'bin', ROOT / 'gon/bin', private, ROOT / 'pkg/include'):
        files.update(path for path in directory.rglob('*') if path.is_file())
    manifest = {
        'version': args.version,
        'sourceCommit': output('git', 'rev-parse', 'HEAD'),
        'platform': platform,
        'toolchainVersion': target['GOVERSION'],
        'compilerSHA256': hashlib.sha256((private / ('compile' + suffix)).read_bytes()).hexdigest(),
        'upstream': json.loads((ROOT / 'misc/gon/UPSTREAM.json').read_text()),
    }
    stem = 'gon-' + args.version
    archive_name = stem + '-' + platform + ('.zip' if os.name == 'nt' else '.tar.gz')
    archive_path = args.output / archive_name
    # VERSION must travel with the toolchain; VERSION.cache is local build state.
    extras = {'VERSION': (target['GOVERSION'] + '\n').encode(),
              'GON_RELEASE.json': (json.dumps(manifest, indent=2) + '\n').encode()}
    import io
    if os.name == 'nt':
        with zipfile.ZipFile(archive_path, 'w', zipfile.ZIP_DEFLATED) as archive:
            for path in sorted(files):
                archive.write(path, stem + '/' + path.relative_to(ROOT).as_posix())
            for name, data in extras.items():
                archive.writestr(stem + '/' + name, data)
    else:
        with tarfile.open(archive_path, 'w:gz') as archive:
            for path in sorted(files):
                archive.add(path, arcname=stem + '/' + path.relative_to(ROOT).as_posix(), recursive=False)
            for name, data in extras.items():
                info = tarfile.TarInfo(stem + '/' + name)
                info.size, info.mode = len(data), 0o644
                archive.addfile(info, io.BytesIO(data))
    checksum = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    (args.output / (archive_name + '.sha256')).write_text(checksum + '  ' + archive_name + '\n')
    print(archive_path)


if __name__ == '__main__':
    main()
